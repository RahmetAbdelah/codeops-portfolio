const API = "https://open.er-api.com/v6/latest/ETB";
const KEY = "birrwatch";

// Single state object as the source of truth
const state = {
  base: "ETB",
  rates:JSON.parse(json),
  watchlist: [],
  amount: 100,
  currency: "USD",
};

// DOM references
const statusEl = document.querySelector("#status");
const form = document.querySelector("#convert-form");
const amountInput = document.querySelector("#amount");
const select = document.querySelector("#currency");
const resultEl = document.querySelector("#result");
const addBtn = document.querySelector("#watch");
const watchUl = document.querySelector("#watchlist");

// Load saved data from localStorage on startup
function load() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved) {
      Object.assign(state, JSON.parse(saved));
    }
  } catch (err) {
    console.error("Failed to load state from localStorage:", err);
  }
}

// Persist state subset to localStorage
function save() {
  localStorage.setItem(
    KEY,
    JSON.stringify({
      watchlist: state.watchlist,
      currency: state.currency,
    })
  );
}

// Fetch live rates from the public API
async function loadRates() {
  statusEl.textContent = "Loading rates...";
  try {
    const res = await fetch(API);
    if (!res.ok) throw new Error("HTTP " + res.status);
    const data = await res.json();
    state.rates = data.rates;
    statusEl.textContent = "";
  } catch (err) {
    statusEl.textContent = "Could not load rates.";
    console.error(err);
  }
}

// Render dropdown and watchlist from state
function render() {
  const codes = Object.keys(state.rates);
  
  if (codes.length > 0) {
    select.innerHTML = codes
      .map((c) => `<option value="${c}">${c}</option>`)
      .join("");
    select.value = state.currency;
  }

  renderWatchlist();
}

// Render watchlist items
function renderWatchlist() {
  if (state.watchlist.length === 0) {
    watchUl.innerHTML = "<li>No currencies yet</li>";
    return;
  }

  watchUl.innerHTML = state.watchlist
    .map((c) => {
      const r = state.rates[c] ? state.rates[c] : "N/A";
      return `<li data-c="${c}">
        <span>1 ETB = ${r} ${c}</span>
        <button class="rm" aria-label="Remove ${c}">×</button>
      </li>`;
    })
    .join("");
}

// Event Listeners
form.addEventListener("submit", (e) => {
  e.preventDefault();
  const amt = Number(amountInput.value);

  if (!amt ||  amt <= 0  || isNaN(amt)) {
    resultEl.textContent = "Enter a valid amount.";
    return;
  }

  state.currency = select.value;
  state.amount = amt;
  save();

  const rate = state.rates[state.currency];
  if (!rate) {
    resultEl.textContent = "Rate unavailable.";
    return;
  }

  const out = (amt * rate).toFixed(2);
  resultEl.textContent =` ${amt} ETB = ${out} ${state.currency}`;
});

addBtn.addEventListener("click", () => {
  const c = select.value;
  if (!c || state.watchlist.includes(c)) return;

  state.watchlist.push(c);
  save();
  renderWatchlist();
});

// Event delegation for removal buttons
watchUl.addEventListener("click", (e) => {
  if (!e.target.matches(".rm")) return;

  const li = e.target.closest("li");
  const c = li ? li.dataset.c : null;

  if (c) {
    state.watchlist = state.watchlist.filter((x) => x !== c);
    save();
    renderWatchlist();
  }
});

// Main initialization flow
async function init() {
  load();
  await loadRates();
  render();
}

init();